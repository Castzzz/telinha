// Testa os mesmos controles em tamanhos de celular e desktop com Electron do sistema.
const { app, BrowserWindow } = require('electron');
const path = require('node:path');
const fs = require('node:fs/promises');
const os = require('node:os');
const { registerAppScheme, handleAppProtocol, roomUrl } = require('../electron/app-protocol.cjs');
registerAppScheme();
app.commandLine.appendSwitch('autoplay-policy', 'no-user-gesture-required');
app.commandLine.appendSwitch('use-fake-ui-for-media-stream');
app.commandLine.appendSwitch('use-fake-device-for-media-stream');
app.on('window-all-closed', () => {});
const profile = require('node:fs').mkdtempSync(path.join(os.tmpdir(), 'teletela-mobile-test-'));
app.setPath('userData', profile);
let server, io;
const pause = ms => new Promise(resolve => setTimeout(resolve, ms));
app.whenReady().then(async () => {
  const backend = await import('../server.js');
  server = await backend.startServer(0, '127.0.0.1'); io = backend.io;
  handleAppProtocol();
  let win = new BrowserWindow({ width: 390, height: 844, show: false, webPreferences: { offscreen: true, backgroundThrottling: false } });
  const errors = [];
  win.webContents.on('console-message', event => { if (event.level === 'error') { errors.push(event.message); console.error('[Interface]', event.sourceId, event.lineNumber, event.message); } });
  await win.loadURL(roomUrl(`http://127.0.0.1:${server.address().port}`));
  await pause(800);
  const result = await win.webContents.executeJavaScript(`(async () => {
    const check = (ok, message) => { if (!ok) throw new Error(message); };
    const pause = ms => new Promise(resolve => setTimeout(resolve, ms));
    document.querySelectorAll('.modal-backdrop').forEach(el => el.classList.add('hidden'));
    check(!appState.currentChannelId, 'Abrir no celular não deve entrar na call');
    check(document.body.dataset.mobileView === 'canais', 'Canais deve ser a tela inicial');
    check(document.documentElement.scrollWidth <= innerWidth, 'A página não pode transbordar na horizontal');
    document.querySelector('.mobile-nav [data-mobile-view="canais"]').click();
    check(document.body.dataset.mobileView === 'canais', 'A lista de canais precisa abrir');
    document.querySelector('#channel-geral .channel-row').click(); await pause(500);
    check(appState.currentChannelId === 'geral' && document.body.dataset.mobileView === 'sala', 'Entrar no canal deve abrir a sala');
    document.querySelector('#mobile-open-chat').click();
    check(document.body.dataset.mobileView === 'chat', 'Chat precisa abrir por toque');
    check(document.querySelector('#chat-drawer').getBoundingClientRect().width > innerWidth - 40, 'Chat precisa ocupar a largura disponível');
    document.querySelector('#chat-input').value = 'Mensagem pelo celular';
    document.querySelector('#chat-form').dispatchEvent(new Event('submit', {cancelable: true,bubbles: true})); await pause(300);
    check(document.querySelector('#chat-messages').textContent.includes('Mensagem pelo celular'), 'A mensagem precisa aparecer na conversa');
    document.querySelector('.mobile-message-more').click();
    check(document.querySelector('#mobile-message-options').open, 'As ações da mensagem precisam abrir em uma folha');
    const reply = [...document.querySelectorAll('#mobile-message-actions button')].find(button => button.textContent === 'Responder');
    check(reply, 'A ação de responder precisa continuar disponível'); reply.click();
    check(!document.querySelector('#chat-reply-bar').classList.contains('hidden'), 'O menu móvel precisa acionar a resposta original');
    document.querySelector('#btn-cancel-reply').click();
    document.querySelector('.mobile-message-more').click();
    [...document.querySelectorAll('#mobile-message-actions button')].find(button => button.textContent === 'Reagir').click();
    document.querySelector('.msg-react-quick [data-emoji]').click(); await pause(200);
    check(document.querySelector('#chat-messages .chat-reaction'), 'O menu móvel precisa preservar as reações');
    document.querySelector('#mobile-back').click();
    check(document.body.dataset.mobileView === 'sala', 'Fechar o chat deve voltar à sala');
    document.querySelector('#mobile-call-controls [data-mobile-proxy="btn-toggle-mic"]').click(); await pause(900);
    check(appState.myUser.isMicOn && appState.localMicStream, 'O botão de mic precisa capturar áudio');
    document.querySelector('#mobile-call-controls [data-mobile-proxy="btn-toggle-mic"]').click();
    check(!appState.localMicStream.getAudioTracks()[0].enabled, 'Mute precisa silenciar a faixa');
    const controls = document.querySelector('#mobile-call-controls').getBoundingClientRect();
    check(controls.width >= innerWidth - 1 && controls.height >= 100 && controls.bottom <= innerHeight, 'A call precisa de controles grandes e dentro da tela');
    check(getComputedStyle(document.querySelector('#user-dock')).display === 'none', 'O dock de PC não deve ocupar o celular');
    document.querySelector('#mobile-call-more').click();
    check(document.querySelector('#mobile-call-options').open, 'Opções de áudio precisam abrir em uma folha');
    document.querySelector('#mobile-close-options').click();
    document.querySelector('#mobile-back').click();
    check(document.body.dataset.mobileView === 'canais', 'Minimizar a call deve voltar aos canais');
    const bar = document.querySelector('#mobile-callbar').getBoundingClientRect();
    check(bar.height > 0 && bar.height <= 64, 'A call minimizada não pode ocupar duas linhas de controles');
    document.querySelector('.mobile-nav [data-mobile-view="voce"]').click();
    check(getComputedStyle(document.querySelector('#mobile-profile-page')).display !== 'none', 'Você precisa ter uma página própria');
    document.querySelector('#mobile-profile-page [data-mobile-settings="microfone"]').click(); await pause(80);
    check(document.querySelector('#modal-settings').getBoundingClientRect().width <= innerWidth, 'Configurações precisam caber no celular');
    check(getComputedStyle(document.querySelector('.settings-nav')).display === 'none', 'A página de microfone não deve mostrar todas as abas do desktop');
    check(document.querySelector('#modal-settings-title').textContent === 'Microfone', 'A página deve identificar o assunto aberto');
    document.querySelector('[data-close-modal="modal-settings"]').click();
    check(!document.querySelector('#btn-open-account') && !document.querySelector('#btn-open-friends'), 'Contas e amigos ficam na branch futura');
    document.querySelector('.mobile-nav [data-mobile-view="canais"]').click();
    document.querySelector('#mobile-return-call').click();
    check(document.body.dataset.mobileView === 'sala', 'A faixa precisa reabrir a call');
    document.querySelector('#mobile-call-controls [data-mobile-proxy="btn-dock-leave"]').click(); await pause(200);
    check(!appState.currentChannelId, 'Sair da call precisa funcionar');
    check(getComputedStyle(document.querySelector('#mobile-callbar')).display === 'none', 'A faixa deve desaparecer ao sair da call');
    window.TeletelaAndroid = { setCallState() {} };
    document.querySelector('#channel-geral .channel-row').click(); await pause(300);
    document.querySelector('#mobile-call-controls [data-mobile-proxy="btn-toggle-mic"]').click(); await pause(700);
    const androidTrack = appState.localMicStream.getAudioTracks()[0];
    document.querySelector('#mobile-call-controls [data-mobile-proxy="btn-dock-leave"]').click(); await pause(100);
    check(androidTrack.readyState === 'ended' && !appState.localMicStream, 'Android precisa liberar a captura ao sair da call');
    check(appState.myUser.isMicOn, 'Liberar a captura não deve esquecer a escolha do botão');
    document.querySelector('#channel-geral .channel-row').click(); await pause(900);
    check(appState.localMicStream?.getAudioTracks()[0].enabled, 'Voltar à call precisa reabrir o mic escolhido');
    document.querySelector('#mobile-call-controls [data-mobile-proxy="btn-dock-leave"]').click(); await pause(100);
    return { mobile: true, mute: true, chat: true, navigation: true };
  })()`);
  for (const width of [360, 760, 1280]) {
    win.setSize(width, 844); await pause(150);
    const layout = await win.webContents.executeJavaScript(`({ overflow: document.documentElement.scrollWidth > innerWidth, nav: getComputedStyle(document.querySelector('.mobile-nav')).display, width: innerWidth })`);
    if (layout.overflow || (width === 1280 && layout.nav !== 'none')) throw new Error('Layout inválido: ' + JSON.stringify(layout));
    if (width === 1280) {
      const desktop = await win.webContents.executeJavaScript("({dock:getComputedStyle(document.querySelector('#user-dock')).display,header:getComputedStyle(document.querySelector('.app-topbar')).display,settings:getComputedStyle(document.querySelector('.settings-nav')).display})");
      if (desktop.dock === 'none' || desktop.header === 'none' || desktop.settings === 'none') throw new Error('O desktop perdeu seus controles');
    }
  }
  win.webContents.debugger.attach('1.3');
  await win.webContents.debugger.sendCommand('Emulation.setTouchEmulationEnabled', { enabled: true });
  win.setSize(844, 390); await pause(150);
  const landscape = await win.webContents.executeJavaScript("getComputedStyle(document.querySelector('.mobile-nav')).display");
  if (landscape === 'none') throw new Error('Celular deitado precisa manter a navegação por toque');
  win.webContents.debugger.detach();
  const pipTest = (await fs.readFile(path.join(__dirname, 'helpers/mobile-pip-browser.js'))).toString('base64');
  Object.assign(result, await win.webContents.executeJavaScript(`import('data:text/javascript;base64,${pipTest}').then(m => m.run())`));
  // Fecha a janela de verdade: a escolha precisa vir do armazenamento na próxima abertura.
  const reopen = async () => {
    win.destroy();
    win = new BrowserWindow({ width: 1280, height: 844, show: false, webPreferences: { offscreen: true, backgroundThrottling: false } });
    win.webContents.on('console-message', event => { if (event.level === 'error') { errors.push(event.message); console.error('[Interface]', event.sourceId, event.lineNumber, event.message); } });
    await win.loadURL(roomUrl(`http://127.0.0.1:${server.address().port}`));
    for (let i = 0; i < 50; i++) {
      if (await win.webContents.executeJavaScript('Boolean(window.appState && document.querySelector("#channel-geral .channel-row"))')) break;
      await pause(100);
    }
    await win.webContents.executeJavaScript("document.querySelectorAll('.modal-backdrop').forEach(el => el.classList.add('hidden'))");
  };
  const check = async (expression, message) => {
    if (!await win.webContents.executeJavaScript(expression)) throw new Error(message);
  };
  const click = async selector => {
    await win.webContents.executeJavaScript(`document.querySelector(${JSON.stringify(selector)}).click()`);
    await pause(500);
  };
  await reopen();
  await check('appState.myUser.isMicOn && !appState.currentChannelId && !appState.localMicStream', 'Reabrir desmutado deve restaurar a escolha sem entrar na call nem capturar');
  await check('!document.querySelector("#btn-toggle-mic").classList.contains("active-muted")', 'O botão precisa mostrar o estado restaurado');
  await click('#channel-geral .channel-row');
  await check('appState.localMicStream?.getAudioTracks()[0].enabled', 'Entrar após reabrir desmutado precisa abrir o microfone de verdade');
  io.to(await win.webContents.executeJavaScript('appState.myId')).emit('server-moderation', { serverMuted: true });
  await pause(100);
  await check('!appState.myUser.isMicOn && JSON.parse(localStorage.telinha_prefs).micOn', 'Moderação deve mutar sem sobrescrever a escolha salva');
  io.to(await win.webContents.executeJavaScript('appState.myId')).emit('server-moderation', { serverMuted: false });
  await pause(100);
  await click('#btn-toggle-mic');
  await reopen();
  await check('!appState.myUser.isMicOn && !appState.localMicStream', 'Reabrir mutado precisa manter o mute');
  await click('#channel-geral .channel-row');
  await check('!appState.localMicStream', 'Entrar mutado não deve abrir a captura');
  await click('#btn-toggle-mic');
  await click('#btn-toggle-deafen');
  await reopen();
  await check('!appState.myUser.isMicOn', 'Fechar ensurdecido deve reabrir com o microfone mutado');
  await click('#channel-geral .channel-row');
  await click('#btn-toggle-mic');
  await click('#btn-toggle-deafen');
  await click('#btn-toggle-deafen');
  await reopen();
  await check('appState.myUser.isMicOn && !appState.localMicStream', 'Restaurar o áudio antes de fechar deve guardar o mic recuperado');
  await fs.writeFile(path.join(os.tmpdir(), 'teletela-mic-restaurado.png'), (await win.webContents.capturePage()).toPNG());
  result.micAfterReopen = true;
  if (errors.length) throw new Error(errors.join('\n'));
  console.log('Celular e desktop passaram:', JSON.stringify(result));
  await finish(0);
}).catch(async err => { console.error(err); await finish(1); });
const timeout = setTimeout(() => { console.error('Teste móvel excedeu 45 segundos.'); finish(1); }, 45000);
async function finish(code) {
  clearTimeout(timeout);
  BrowserWindow.getAllWindows().forEach(win => win.destroy());
  await new Promise(resolve => io ? io.close(resolve) : resolve());
  await fs.rm(profile, {recursive: true, force: true});
  app.exit(code);
}
